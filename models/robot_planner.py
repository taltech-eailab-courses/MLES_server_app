"""Custom LLM: robot task planner.

A small LLM (Qwen2.5-0.5B-Instruct) fine-tuned with LoRA to turn a natural-language
request into a JSON plan for a mobile robot, exported to GGUF and served with
llama-cpp-python.

Model file: models/robot-q4_k_m.gguf by default. Override with the environment
variable ROBOT_PLANNER_GGUF, e.g. to test the 16-bit file:
    ROBOT_PLANNER_GGUF=/path/to/robot-f16.gguf python app.py

The model is loaded on the first request, so the rest of the app starts even when
the file is not there yet.
"""
import json
import os
import threading
import time
from typing import Optional

from pydantic import BaseModel, Field

robot_plan_title = "Robot Planner (custom fine-tuned LLM)"
robot_plan_description = (
    "A small LLM fine-tuned with LoRA turns a request such as *bring the keys to the front door* "
    "into a JSON plan of robot steps: navigate(target), grab(object), drop(object), stop."
)

# Must be identical to the system prompt used for fine-tuning (make_data.py: SYSTEM).
SYSTEM_PROMPT = (
    "You are the planner of a mobile robot. Convert the user's request into a JSON object "
    "{\"steps\": [...]}. Allowed actions: navigate(target), grab(object), drop(object), stop. "
    "Reply with JSON only."
)

MODEL_PATH = os.environ.get(
    "ROBOT_PLANNER_GGUF", os.path.join(os.path.dirname(os.path.abspath(__file__)), "robot-q4_k_m.gguf")
)
N_GPU_LAYERS = int(os.environ.get("ROBOT_PLANNER_GPU_LAYERS", "-1"))  # -1 = all layers on GPU/Metal
N_THREADS = int(os.environ.get("ROBOT_PLANNER_THREADS", "6"))

# action -> required argument (None = no argument)
ALLOWED_ACTIONS = {"navigate": "target", "grab": "object", "drop": "object", "stop": None}


class RobotPlanRequest(BaseModel):
    request: str = Field(..., min_length=1, max_length=500,
                         description="Natural-language command for the robot",
                         examples=["bring the keys to the front door"])
    max_tokens: int = Field(200, ge=16, le=512, description="Upper limit on generated tokens")


class RobotPlanResponse(BaseModel):
    data: Optional[dict] = Field(None, description='The validated plan {"steps": [...]}; null if the output was invalid')
    valid: bool = Field(..., description="True if the output is valid JSON with only allowed actions")
    error: Optional[str] = Field(None, description="Why the output was rejected, if it was")
    raw: str = Field(..., description="Exact text generated by the model")
    latency_ms: float = Field(..., description="Model inference time")
    model: str = Field(..., description="GGUF file that produced the plan")


class ModelNotAvailable(RuntimeError):
    pass


_llm = None
_lock = threading.Lock()  # llama.cpp contexts are not thread-safe; FastAPI runs sync endpoints in threads


def _get_llm():
    global _llm
    if _llm is None:
        if not os.path.isfile(MODEL_PATH):
            raise ModelNotAvailable(
                f"Model file not found: {MODEL_PATH}. Copy robot-q4_k_m.gguf into models/ "
                f"or set ROBOT_PLANNER_GGUF to its path."
            )
        from llama_cpp import Llama  # imported here so the app starts without the model
        _llm = Llama(
            model_path=MODEL_PATH,
            n_ctx=1024,
            n_gpu_layers=N_GPU_LAYERS,
            n_threads=N_THREADS,
            seed=42,
            verbose=False,
        )  # the chat template stored in the GGUF file is used automatically
    return _llm


def parse_plan(text: str):
    """Return (plan_dict, None) if the text is a valid plan, else (None, reason)."""
    s = text.strip()
    if s.startswith("```"):  # tolerate ```json ... ``` fences
        s = s.strip("`")
        s = s[s.find("{"):] if "{" in s else s
    start, end = s.find("{"), s.rfind("}")
    if start < 0 or end < start:
        return None, "no JSON object in output"
    try:
        obj = json.loads(s[start:end + 1])
    except json.JSONDecodeError as e:
        return None, f"invalid JSON: {e.msg}"
    steps = obj.get("steps") if isinstance(obj, dict) else None
    if not isinstance(steps, list) or not steps:
        return None, "missing or empty 'steps' list"
    for i, step in enumerate(steps):
        if not isinstance(step, dict) or step.get("action") not in ALLOWED_ACTIONS:
            return None, f"step {i}: unknown action {step.get('action') if isinstance(step, dict) else step!r}"
        arg = ALLOWED_ACTIONS[step["action"]]
        if arg and not isinstance(step.get(arg), str):
            return None, f"step {i}: '{step['action']}' needs a '{arg}'"
    return {"steps": steps}, None


def robot_plan(request: str, max_tokens: int = 200) -> dict:
    llm = _get_llm()
    messages = [{"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": request}]
    with _lock:
        t0 = time.perf_counter()
        out = llm.create_chat_completion(messages=messages, temperature=0.0, max_tokens=max_tokens)
        latency_ms = (time.perf_counter() - t0) * 1000
    raw = out["choices"][0]["message"]["content"] or ""
    plan, err = parse_plan(raw)
    return {"data": plan, "valid": plan is not None, "error": err, "raw": raw,
            "latency_ms": round(latency_ms, 1), "model": os.path.basename(MODEL_PATH)}
